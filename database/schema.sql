-- 投融资对接平台数据库建表脚本
-- 基于实体类生成

-- 创建数据库（如果不存在）
CREATE DATABASE IF NOT EXISTS investment DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE investment;

-- 1. 用户表
CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    phone VARCHAR(20) NOT NULL UNIQUE COMMENT '手机号',
    password_hash VARCHAR(255) NOT NULL COMMENT '密码哈希',
    email VARCHAR(100) COMMENT '邮箱',
    user_type VARCHAR(20) NOT NULL COMMENT '用户类型: INVESTOR/ENTREPRENEUR',
    real_name VARCHAR(50) COMMENT '真实姓名',
    avatar_url VARCHAR(500) COMMENT '头像URL',
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' COMMENT '状态: PENDING/ACTIVE/INACTIVE/BANNED',
    is_verified BOOLEAN DEFAULT FALSE COMMENT '是否实名认证',
    last_login_at DATETIME COMMENT '最后登录时间',
    last_viewed_project_id BIGINT COMMENT '最后查看的项目ID',
    last_viewed_teaser_id BIGINT COMMENT '最后查看的Teaser ID',
    notification_count INT DEFAULT 0 COMMENT '未读通知数量',
    unread_question_count INT DEFAULT 0 COMMENT '未读问题数量',
    profile_completion_rate INT DEFAULT 0 COMMENT '资料完善度百分比',
    preferences JSON COMMENT '用户偏好设置',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME COMMENT '软删除时间',
    INDEX idx_phone (phone),
    INDEX idx_email (email),
    INDEX idx_user_type (user_type),
    INDEX idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户表';

-- 2. 投资人资料表
CREATE TABLE IF NOT EXISTS investor_profiles (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    user_id BIGINT NOT NULL UNIQUE COMMENT '用户ID',
    avatar_url VARCHAR(500) COMMENT '头像URL',
    institution_name VARCHAR(200) COMMENT '机构名称',
    position VARCHAR(100) COMMENT '职位',
    department VARCHAR(100) COMMENT '部门',
    work_years INT COMMENT '从业年限',
    institution_type VARCHAR(50) COMMENT '机构类型',
    investment_stage VARCHAR(255) COMMENT '投资阶段偏好',
    investment_industries VARCHAR(255) COMMENT '投资行业偏好',
    investment_region VARCHAR(255) COMMENT '投资地区偏好',
    investment_range_min DECIMAL(12,2) COMMENT '最小投资金额(万)',
    investment_range_max DECIMAL(12,2) COMMENT '最大投资金额(万)',
    phone VARCHAR(20) COMMENT '联系电话',
    wechat VARCHAR(100) COMMENT '微信号',
    introduction TEXT COMMENT '个人/机构简介',
    investment_philosophy TEXT COMMENT '投资理念',
    notable_investments TEXT COMMENT '知名投资案例',
    website_url VARCHAR(500) COMMENT '官网URL',
    linkedin_url VARCHAR(500) COMMENT '领英链接',
    investment_score INT DEFAULT 50 COMMENT '投资评分(0-100)',
    activity_level VARCHAR(20) DEFAULT 'medium' COMMENT '活跃度',
    response_rate DECIMAL(5,2) COMMENT '回复率(%)',
    avg_response_time INT COMMENT '平均回复时间(小时)',
    investment_count INT DEFAULT 0 COMMENT '投资项目数',
    followers_count INT DEFAULT 0 COMMENT '关注者数量',
    is_verified BOOLEAN DEFAULT FALSE COMMENT '是否已认证',
    verification_level VARCHAR(20) DEFAULT 'basic' COMMENT '认证等级',
    preferences JSON COMMENT '投资偏好设置',
