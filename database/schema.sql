    project_name VARCHAR(200) NOT NULL COMMENT '项目名称',
    project_code VARCHAR(50) UNIQUE COMMENT '项目编码',
    industry VARCHAR(50) COMMENT '所属行业',
    location VARCHAR(100) COMMENT '项目所在地',
    company_founded_date DATE COMMENT '公司成立日期',
    office_address VARCHAR(500) COMMENT '办公地址',
    company_website VARCHAR(255) COMMENT '公司官网',
    financing_stage VARCHAR(20) COMMENT '融资阶段',
    financing_amount DECIMAL(12,2) COMMENT '融资金额(万)',
    valuation DECIMAL(15,2) COMMENT '估值(万)',
    equity_percentage DECIMAL(5,2) COMMENT '出让股权比例(%)',
    financing_history TEXT COMMENT '融资历史',
    one_line_description VARCHAR(500) COMMENT '一句话描述',
    business_description TEXT COMMENT '业务描述',
    logo_url VARCHAR(500) COMMENT '公司logo URL',
    business_plan_file_url VARCHAR(500) COMMENT '商业计划书文件URL',
    market_size TEXT COMMENT '市场规模',
    competitive_advantage TEXT COMMENT '竞争优势',
    contact_person VARCHAR(100) COMMENT '联系人',
    contact_phone VARCHAR(20) COMMENT '联系电话',
    contact_email VARCHAR(100) COMMENT '联系邮箱',
    business_model TEXT COMMENT '商业模式',
    revenue_ytd DECIMAL(12,2) COMMENT '当年营收(万)',
    revenue_last_year DECIMAL(12,2) COMMENT '去年营收(万)',
    gross_margin DECIMAL(5,2) COMMENT '毛利率(%)',
    team_size INT COMMENT '团队规模',
    status VARCHAR(20) DEFAULT 'DRAFT' COMMENT '状态: DRAFT/SUBMITTED/ACTIVE/FINANCED/ARCHIVED',
    is_anonymous BOOLEAN DEFAULT TRUE COMMENT '是否匿名显示',
    view_count INT DEFAULT 0 COMMENT '浏览次数',
    favorite_count INT DEFAULT 0 COMMENT '收藏次数',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME,
    FOREIGN KEY (entrepreneur_user_id) REFERENCES users(id),
    INDEX idx_entrepreneur_user_id (entrepreneur_user_id),
    INDEX idx_project_code (project_code),
    INDEX idx_industry (industry),
    INDEX idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='项目表';

-- 5. 商业计划书表
CREATE TABLE IF NOT EXISTS business_plans (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    project_id BIGINT NOT NULL COMMENT '项目ID',
    file_name VARCHAR(255) NOT NULL COMMENT '文件名',
    file_url VARCHAR(500) NOT NULL COMMENT '文件URL',
    thumbnail_url VARCHAR(500) COMMENT '缩略图URL',
    file_size INT COMMENT '文件大小(字节)',
    page_count INT COMMENT '页数',
    file_format VARCHAR(10) COMMENT '文件格式',
    file_hash VARCHAR(64) COMMENT '文件哈希值',
    upload_status VARCHAR(20) DEFAULT 'UPLOADING' COMMENT '上传状态: UPLOADING/COMPLETED/FAILED',
    upload_source VARCHAR(20) DEFAULT 'web' COMMENT '上传来源',
    teaser_generation_status VARCHAR(20) DEFAULT 'PENDING' COMMENT 'Teaser生成状态',
    extraction_status VARCHAR(20) DEFAULT 'PENDING' COMMENT '内容提取状态',
    extracted_content JSON COMMENT '提取的内容',
    ai_analysis_status VARCHAR(20) DEFAULT 'PENDING' COMMENT 'AI分析状态',
    analysis_id BIGINT COMMENT '关联的分析记录ID',
    teaser_id BIGINT COMMENT '关联的Teaser ID',
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME,
    FOREIGN KEY (project_id) REFERENCES projects(id),
    INDEX idx_project_id (project_id),
    INDEX idx_upload_status (upload_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='商业计划书表';

