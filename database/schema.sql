    FOREIGN KEY (entrepreneur_user_id) REFERENCES users(id),
    INDEX idx_project_id (project_id),
    INDEX idx_investor_user_id (investor_user_id),
    INDEX idx_entrepreneur_user_id (entrepreneur_user_id),
    INDEX idx_question_status (question_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='问答记录表';

